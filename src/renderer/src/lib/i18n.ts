export type Dict = typeof zh

const dict: Record<'zh' | 'en', Dict> = { zh, en }

/** 当前语言字典 */
export function useT(): Dict {
  const lang = useApp((s) => s.settings.language)
  return dict[lang]
}

/** 是否显示数据库色标 */
export function useShowDbColor(): boolean {
  return useApp((s) => s.settings.showDbColorLabels)
}
